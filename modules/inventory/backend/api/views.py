class StockReclassificationViewSet(viewsets.ViewSet):







    """Read-only lookups that drive the Create Stock Reclassification form."""















    @action(detail=False, methods=["get"])







    def eligibility(self, request):







        from services import stock_reclassification as rules















        p = request.query_params







        item = InventoryItem.objects.select_related("base_uom").filter(pk=p.get("item")).first() if str(p.get("item") or "").isdigit() else None







        if item is None:







            return Response({"error": "Select a valid item."}, status=status.HTTP_400_BAD_REQUEST)







        variant = InventoryItemVariant.objects.filter(pk=p.get("variant"), item=item).first() if p.get("variant") else None







        warehouse = Warehouse.objects.filter(pk=p.get("warehouse")).first() if str(p.get("warehouse") or "").isdigit() else None







        location = None







        if p.get("location"):







            location = StorageLocation.objects.filter(pk=p.get("location")).first()







            if location is None or (warehouse and location.warehouse_id != warehouse.id):







                return Response({"error": "Location does not belong to the selected warehouse."}, status=status.HTTP_400_BAD_REQUEST)







        from_status = (p.get("from_status") or "AVAILABLE").upper()







        if from_status not in rules.STATUSES:







            return Response({"error": "Unknown source status."}, status=status.HTTP_400_BAD_REQUEST)







        on_date = parse_date(p.get("effective_date") or "") or timezone.localdate()







        cfg = rules.config()







        flags = rules.tracking_flags(item)















        payload = {







            "item": {







                "id": item.id, "code": item.code, "name": item.name, "uom": rules.uom_rules(item), "tracking": flags,







                "variants": [{"id": v.id, "sku": v.sku, "name": v.variant_name} for v in item.variants.filter(is_active=True)],







            },







            "source_status": from_status,







            "permitted_statuses": cfg["permitted_statuses"],







            "permitted_targets": rules.permitted_targets(from_status),







            "allow_location_change": cfg["allow_location_change"],







            "target_location_types": cfg["target_location_types"],







            "approval_required": cfg.get("approval_required", False),







            "balance": None,







            "eligible_quantity": "0",







            "batches": [],







            "serials": [],







        }







        if warehouse is None:







            return Response(payload)



















        balance = StockBalance.objects.filter(item=item, variant=variant, warehouse=warehouse, location=location).first()







        payload["balance"] = {







            "on_hand": str(balance.on_hand_qty if balance else 0),







            "reserved": str(balance.reserved_qty if balance else 0),







            **{s.lower(): str(rules.bucket_qty(balance, s)) for s in rules.STATUSES},







        }







        bucket = rules.bucket_qty(balance, from_status)







        payload["eligible_quantity"] = str(bucket)







        if flags["batch"]:







            for b in rules.eligible_batches(item, variant, warehouse, location, from_status, on_date):







                expired = rules.is_expired(b, on_date)







                payload["batches"].append({







                    "batch_number": b.batch_number,







                    "expiry_date": b.expiry_date,







                    "expired": expired,







                    "batch_status": b.batch_status,







                    "remaining_quantity": str(b.remaining_quantity),







                    "eligible_quantity": str(min(bucket, b.remaining_quantity)),







                    "permitted_targets": rules.permitted_targets(from_status, expired),







                })







        if flags["serial"]:







            batch = None







            if p.get("batch_number"):







                batch = rules.eligible_batches(item, variant, warehouse, location, from_status, on_date).filter(







                    batch_number=p["batch_number"]







                ).first()







            payload["serials"] = [







                {"serial_number": sn.serial_number, "batch_number": sn.batch.batch_number if sn.batch_id else "", "status": sn.status}







                for sn in rules.eligible_serials(item, variant, warehouse, location, from_status, batch).select_related("batch")[:500]







            ]







        return Response(payload)


