                reserved = Decimal(str(bal.get("total_reserved") or 0))







                blocked = Decimal(str(bal.get("total_blocked") or 0))







                quarantined = Decimal(str(bal.get("total_quarantined") or 0))







                damaged = Decimal(str(bal.get("total_damaged") or 0))







                available = max(Decimal("0.0000"), on_hand - reserved - blocked - quarantined - damaged)















                level = levels_map.get((item.id, wh.id))







                rule = rules_map.get((item.id, wh.id))















                min_stock = level.min_stock if level else Decimal("0.0000")







