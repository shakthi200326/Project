    # Posted or reversed documents are immutable; receipts can only be edited while DRAFT.







    def _guard_mutation(self, tx):







        if tx.status in (StockTransaction.Status.POSTED, StockTransaction.Status.REVERSED):







            return Response(







                {"error": f"{tx.document_number} is {tx.get_status_display()} and cannot be changed; reverse it instead."},







                status=status.HTTP_400_BAD_REQUEST,







            )







        if tx.transaction_type == StockTransaction.TransactionType.RECEIPT and tx.status != StockTransaction.Status.DRAFT:







            return Response(







                {"error": f"Goods receipt {tx.document_number} can only be edited while in draft."},







                status=status.HTTP_400_BAD_REQUEST,







            )







        if tx.transaction_type == StockTransaction.TransactionType.RECLASSIFICATION and tx.status != StockTransaction.Status.DRAFT:







            return Response(







                {"error": f"Reclassification {tx.document_number} can only be deleted while in draft."},







                status=status.HTTP_400_BAD_REQUEST,







            )







        return None















