    @action(detail=False, methods=["post"], url_path="import-preview")







    def import_preview(self, request):







        """Parses uploaded CSV/Excel and returns dry-run validation preview without saving."""







        uploaded_file = request.FILES.get("file")







        if not uploaded_file:







            return Response({"error": "No file uploaded."}, status=status.HTTP_400_BAD_REQUEST)















        filename = uploaded_file.name







        update_existing = request.data.get("update_existing", "true").lower() in ["true", "1"]







        raw_rows = ProductImportExportService.parse_rows(uploaded_file, filename)







        if not raw_rows:







            return Response({"error": "File contains no readable rows or headers."}, status=status.HTTP_400_BAD_REQUEST)















        preview_result = ProductImportExportService.validate_and_preview(







            raw_rows, update_existing=update_existing







        )







        return Response(preview_result)















    @action(detail=False, methods=["post"], url_path="import-commit")







    def import_commit(self, request):







        """Commits pre-validated or directly uploaded data atomically into DB."""







        uploaded_file = request.FILES.get("file")







        update_existing = request.data.get("update_existing", "true").lower() in ["true", "1"]















        if uploaded_file:







            filename = uploaded_file.name







            raw_rows = ProductImportExportService.parse_rows(uploaded_file, filename)







            val_res = ProductImportExportService.validate_and_preview(raw_rows, update_existing=update_existing)







            if val_res["errors"]:







                return Response({







                    "status": "validation_failed",







                    "error": f"Validation failed with {len(val_res['errors'])} row errors.",







                    "details": val_res,







                }, status=status.HTTP_400_BAD_REQUEST)







            validated_rows = val_res["_validated_data"]







        else:







            validated_rows = request.data.get("validated_rows", [])















        if not validated_rows:







            return Response({"error": "No valid rows provided to commit."}, status=status.HTTP_400_BAD_REQUEST)















        actor = getattr(request.user, "username", "system")







        commit_res = ProductImportExportService.commit_import(







            validated_rows, user=actor







        )







        return Response(commit_res)















