class CategoryViewSet(viewsets.ModelViewSet):







    queryset = InventoryCategory.objects.select_related("parent").prefetch_related("children").all()







    serializer_class = CategorySerializer















    def get_queryset(self):







        qs = super().get_queryset()







        context_id = self.request.headers.get("X-Context-ID") or self.request.query_params.get("context_id")







        if context_id:







            qs = qs.filter(context_id=context_id)







        search = self.request.query_params.get("search")







        if search:







            qs = qs.filter(Q(name__icontains=search) | Q(code__icontains=search))







        parent = self.request.query_params.get("parent")







        if parent is not None:







            if parent in ["null", "none", "0"]:







                qs = qs.filter(parent__isnull=True)







            elif parent.isdigit():







                qs = qs.filter(parent_id=int(parent))







        status_param = self.request.query_params.get("is_active")







        if status_param is not None:







            qs = qs.filter(is_active=status_param.lower() in ["true", "1"])







        return qs















    @action(detail=False, methods=["get"])







    def tree(self, request):







        """Returns category hierarchy as nested tree nodes."""







        def build_node(cat):







            children = cat.children.filter(is_active=True)







            return {







                "id": cat.id,







                "code": cat.code,







                "name": cat.name,







                "description": cat.description,







                "image_file_id": cat.image_file_id,







                "is_active": cat.is_active,







                "children": [build_node(child) for child in children],







            }







        root_categories = InventoryCategory.objects.filter(parent__isnull=True, is_active=True)







        return Response([build_node(r) for r in root_categories])















    def destroy(self, request, *args, **kwargs):







        instance = self.get_object()







        item_count = instance.items.count()







        if item_count > 0:







            return Response(







                {"error": f"Cannot delete category '{instance.name}' because {item_count} products depend on it. Please reassign products first."},







                status=status.HTTP_400_BAD_REQUEST,







            )







        return super().destroy(request, *args, **kwargs)























