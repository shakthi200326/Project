    @action(detail=False, methods=["post"], url_path="seed-standard")
    def seed_standard(self, request):
        standard_attributes = [
            {
                "code": "COLOR",
                "name": "Color",
                "is_variant_generator": True,
                "values": ["Red", "Blue", "Green", "Black", "White", "Silver", "Grey"],
            },
            {
                "code": "SIZE",
                "name": "Size",
                "is_variant_generator": True,
                "values": ["Small", "Medium", "Large", "XL", "XXL"],
            },
            {
                "code": "MATERIAL",
                "name": "Material",
                "is_variant_generator": True,
                "values": ["Stainless Steel", "Aluminum", "Brass", "Polyurethane", "Carbon Steel"],
            },
        ]
        created_attrs = []
        for defn in standard_attributes:
            attr, _ = ProductAttribute.objects.update_or_create(
                code=defn["code"],
                defaults={
                    "name": defn["name"],
                    "is_variant_generator": True,
                    "is_active": True,
                },
            )
            for idx, v in enumerate(defn["values"]):
                ProductAttributeValue.objects.get_or_create(
                    attribute=attr,
                    value=v,
                    defaults={"display_order": idx, "is_active": True},
                )
            created_attrs.append(attr)

        item_id = request.data.get("item")
        if item_id:
            try:
                item = InventoryItem.objects.get(pk=item_id)
                for attr in created_attrs:
                    ItemAttributeValue.objects.get_or_create(item=item, attribute=attr, variant=None)
            except InventoryItem.DoesNotExist:
                pass

        return Response({"status": "Standard attributes seeded", "count": len(created_attrs)})























