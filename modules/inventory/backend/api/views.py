    @action(detail=False, methods=["get"], url_path="barcode-lookup")







    def barcode_lookup(self, request):







        """High-speed barcode scanner resolution endpoint (<25ms)."""







        query = (







            request.query_params.get("barcode")







            or request.query_params.get("query")







            or request.query_params.get("code")







            or ""







        ).strip()







        if not query:







            return Response({"found": False, "error": "Query code cannot be empty."}, status=status.HTTP_400_BAD_REQUEST)















        # 1. Check ProductBarcode table







        barcode_rec = (







            ProductBarcode.objects.select_related("item", "variant", "item__base_uom")







            .filter(barcode_value__iexact=query, is_active=True)







            .first()







        )







        if barcode_rec:







            item = barcode_rec.item







            variant = barcode_rec.variant







            return Response({







                "found": True,







                "item_id": item.id,







                "item_code": item.code,







                "item_name": item.name,







                "variant_id": variant.id if variant else None,







                "variant_sku": variant.sku if variant else None,







                "variant_name": variant.variant_name if variant else None,







                "barcode": barcode_rec.barcode_value,







                "symbology": barcode_rec.symbology,







                "barcode_type": barcode_rec.barcode_type,







                "base_uom": item.base_unit or (item.base_uom.code if item.base_uom else "EA"),







                "standard_cost": str(item.standard_cost),







                "list_price": str(item.list_price),







                "is_active": item.is_active and (variant.is_active if variant else True),







            })















        # 2. Check item direct barcode or code







        item = InventoryItem.objects.filter(Q(barcode__iexact=query) | Q(code__iexact=query)).first()







        if item:







            return Response({







                "found": True,







                "item_id": item.id,







                "item_code": item.code,







                "item_name": item.name,







                "variant_id": None,







                "variant_sku": None,







                "variant_name": None,







                "barcode": item.barcode,







                "symbology": "CODE128",







                "barcode_type": "PRIMARY",







                "base_uom": item.base_unit or (item.base_uom.code if item.base_uom else "EA"),







                "standard_cost": str(item.standard_cost),







                "list_price": str(item.list_price),







                "is_active": item.is_active,







            })















        # 3. Check variant direct barcode or sku







        variant = InventoryItemVariant.objects.select_related("item").filter(Q(barcode__iexact=query) | Q(sku__iexact=query)).first()







        if variant:







            item = variant.item







            return Response({







                "found": True,







                "item_id": item.id,







                "item_code": item.code,







                "item_name": item.name,







                "variant_id": variant.id,







                "variant_sku": variant.sku,







                "variant_name": variant.variant_name,







                "barcode": variant.barcode,







                "symbology": "CODE128",







                "barcode_type": "PRIMARY",







                "base_uom": item.base_unit or (item.base_uom.code if item.base_uom else "EA"),







                "standard_cost": str(item.standard_cost + variant.additional_cost),







                "list_price": str(item.list_price + variant.additional_price),







                "is_active": item.is_active and variant.is_active,







            })















        return Response({"found": False, "message": f"No item or variant found matching '{query}'."}, status=status.HTTP_200_OK)















